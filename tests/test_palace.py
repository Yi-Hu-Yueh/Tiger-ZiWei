@pytest.mark.parametrize("hour,minute,branch,life,body", [
    (22, 59, "亥", "申", "午"), (23, 0, "子", "未", "未"),
    (23, 59, "子", "未", "未"), (0, 0, "子", "未", "未"),
])
def test_late_zi_preserves_phase_1b_civil_date(
    hour: int, minute: int, branch: str, life: str, body: str,
) -> None:
    # Use the last day before leap June: advancing at 23:00 would change month.
    cal = calculate_calendar(birth("2025-07-24", hour, minute))
    before = cal.model_dump()
    result = calculate_palaces(cal)
    assert cal.model_dump() == before
    assert cal.solar_date == date(2025, 7, 24)
    assert cal.lunar_date == lunar(6, False, 30)
    assert cal.day_ganzhi.display == "甲午"
    assert result.birth_hour_branch == branch
    assert (result.life_palace_branch, result.body_palace_branch) == (life, body)


def test_uses_lunar_month_not_gregorian_or_month_ganzhi() -> None:
    # Lunar month stays 1 while the solar-term month changes from 丑 to 寅.
    before = calculate_calendar(birth("2025-02-02", 1))
    after = calculate_calendar(birth("2025-02-03", 1))
    assert before.solar_date.month == after.solar_date.month == 2
    assert before.month_ganzhi != after.month_ganzhi
    assert calculate_palaces(before) == calculate_palaces(after)
    assert calculate_palaces(after).life_palace_branch == "丑"


def test_palace_serialization_and_immutable_marker() -> None:
    result = place_palaces(lunar(1), "丑")
    payload = result.model_dump(mode="json")
    assert payload["life_palace_branch"] == "丑"
    assert payload["body_palace_branch"] == "卯"
    assert payload["body_palace_name"] == "福德宮"
    assert len(payload["palaces"]) == 12
    assert sum(p["is_life_palace"] for p in payload["palaces"]) == 1
    assert PalaceLayout.model_validate(result.model_dump(round_trip=True)) == result
    with pytest.raises(ValidationError):
        result.palaces[0].has_body_palace = True


