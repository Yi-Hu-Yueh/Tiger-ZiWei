@pytest.mark.parametrize("defect", ["thirteen", "duplicate_branch", "alias", "bad_host", "two_markers"])
def test_inconsistent_layout_rejected(defect: str) -> None:
    payload = place_palaces(lunar(1), "子").model_dump(round_trip=True)
    positions = [dict(p) for p in payload["palaces"]]
    if defect == "thirteen":
        positions.append(dict(positions[0]))
    elif defect == "duplicate_branch":
        positions[1]["earthly_branch"] = positions[0]["earthly_branch"]
    elif defect == "alias":
        positions[7]["name"] = "僕役宮"
    elif defect == "bad_host":
        positions[0]["has_body_palace"] = False
        positions[1]["has_body_palace"] = True
    else:
        positions[2]["has_body_palace"] = True
    payload["palaces"] = positions
    with pytest.raises(ValidationError):
        PalaceLayout.model_validate(payload)
