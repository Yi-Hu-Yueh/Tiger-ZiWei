@pytest.mark.parametrize("hour,expected_host", [
    ("子", "命宮"), ("丑", "福德宮"), ("寅", "官祿宮"), ("卯", "遷移宮"),
    ("辰", "財帛宮"), ("巳", "夫妻宮"), ("午", "命宮"), ("未", "福德宮"),
    ("申", "官祿宮"), ("酉", "遷移宮"), ("戌", "財帛宮"), ("亥", "夫妻宮"),
])
def test_body_host_invariant_for_every_supported_month(
    hour: EarthlyBranch, expected_host: str,
) -> None:
    # All 12 hours x (12 normal + 11 supported leap month inputs) = 276 layouts.
    legal_hosts = {"命宮", "夫妻宮", "財帛宮", "遷移宮", "官祿宮", "福德宮"}
    for leap in (False, True):
        for month in range(1, 12 if leap else 13):
            result = place_palaces(lunar(month, leap), hour)
            assert result.body_palace_name == expected_host
            assert result.body_palace_name in legal_hosts
            assert len(result.palaces) == 12
            assert {p.earthly_branch for p in result.palaces} == set(EARTHLY_BRANCHES)
            assert len({p.name for p in result.palaces}) == 12
            assert sum(p.has_body_palace for p in result.palaces) == 1
            host = next(p for p in result.palaces if p.has_body_palace)
            assert host.earthly_branch == result.body_palace_branch
            assert host.name == result.body_palace_name


@pytest.mark.parametrize("month", range(1, 12))
def test_leap_month_is_always_next_month(month: int) -> None:
    assert effective_lunar_month(lunar(month)) == month
    assert effective_lunar_month(lunar(month, True)) == month + 1


@pytest.mark.parametrize("day", [1, 15, 16, 29])
def test_leap_sixth_month_has_no_midmonth_split(day: int) -> None:
    value = lunar(6, True, day)
    result = place_palaces(value, "未")
    assert result.effective_lunar_month == 7
    assert (result.life_palace_branch, result.body_palace_branch) == ("丑", "卯")
    assert value.month == 6 and value.is_leap_month  # Input is unchanged.


