@pytest.mark.parametrize("solar,hour,minute,expected_lunar,month,life,body", FULL_INPUT_VECTORS)
def test_full_birth_calendar_palace_integration(
    solar: str, hour: int, minute: int, expected_lunar: tuple[int, int, int, bool],
    month: int, life: str, body: str,
) -> None:
    cal = calculate_calendar(birth(solar, hour, minute))
    value = cal.lunar_date
    assert (value.year, value.month, value.day, value.is_leap_month) == expected_lunar
    result = calculate_palaces(cal)
    assert result.effective_lunar_month == month
    assert (result.life_palace_branch, result.body_palace_branch) == (life, body)


